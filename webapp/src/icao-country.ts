const SPECIAL: Record<string, string> = {
  "-T": "ICAO (temporary address)",
  "-S": "ICAO (special address)",
};

let regionNames: Intl.DisplayNames | null | undefined;
function regionName(code: string): string {
  if (regionNames === undefined) {
    try {
      regionNames = new Intl.DisplayNames(["en"], { type: "region" });
    } catch {
      regionNames = null;
    }
  }
  return regionNames?.of(code) ?? code;
}

export interface IcaoCountry {
  code: string; // ISO 3166 alpha-2, or -T/-S
  name: string; // English
  flag: string; // flag emoji (two regional-indicator symbols), "" for -T/-S
}

export function icaoCountry(hex: string): IcaoCountry | null {
  // "~" prefix = non-ICAO address (TIS-B), as in readsb's aircraft.json
  if (!hex || hex.startsWith("~")) return null;
  const n = parseInt(hex, 16);
  const r = ICAO_RANGES.find(([a, b]) => n >= a && n <= b);
  if (!r) return null;
  const code = r[2];
  if (SPECIAL[code]) return { code, name: SPECIAL[code], flag: "" };
  return {
    code,
    name: regionName(code),
    flag: String.fromCodePoint(...[...code].map((c) => 0x1f1a5 + c.charCodeAt(0))),
  };
}
